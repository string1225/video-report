"""Package local research media and preserve its independent attribution."""
from __future__ import annotations

import copy
import hashlib
import json
from pathlib import Path
import re
import shutil


def package_media(report: dict, output: Path, report_dir: Path) -> dict:
    embedded = copy.deepcopy(report)
    previous_path = output/'media-sources.json'
    previous = json.loads(previous_path.read_text(encoding='utf-8')) if previous_path.exists() else []
    prepared = []
    # Validate all files before changing the presentation or copying assets.
    for asset in embedded.get('media', []):
        source = Path(asset['path'])
        if not source.is_absolute():
            source = Path(report_dir)/source
        if not source.is_file():
            raise ValueError(f"Media asset does not exist: {source}")
        suffix = source.suffix.lower()
        allowed = ('.mp4', '.webm') if asset['type'] == 'video' else ('.png', '.jpg', '.jpeg', '.webp', '.svg')
        if suffix not in allowed:
            raise ValueError(f'Unsupported browser media extension: {source}')
        with source.open('rb') as stream:
            digest = hashlib.file_digest(stream, 'sha256').hexdigest()
        if asset.get('sha256') and digest != asset['sha256'].lower():
            raise ValueError(f"Media SHA-256 checksum mismatch: {asset['id']}")
        asset['sha256'] = digest
        asset['original_path'] = asset.get('original_path', asset['path'])
        asset['path'] = f'media/{digest}{suffix}'
        prepared.append((asset, source))
    if prepared:
        (output/'deck/media').mkdir(parents=True, exist_ok=True)
    for asset, source in prepared:
        target = output/'deck'/asset['path']
        if source.resolve() != target.resolve():
            shutil.copy2(source, target)
    registry = embedded.get('media', [])
    # Only remove content-addressed files generated by the previous manifest.
    # Preserve user additions and reject paths outside this exact media folder.
    keep = {item['path'] for item in registry}
    media_root = (output/'deck/media').resolve()
    for item in previous:
        old = item.get('path', '')
        candidate = (output/'deck'/old).resolve()
        if old not in keep and candidate.parent == media_root and re.fullmatch(r'[a-f0-9]{64}\.(png|jpe?g|webp|svg|mp4|webm)', candidate.name):
            candidate.unlink(missing_ok=True)
    (output/'media-sources.json').write_text(json.dumps(registry, ensure_ascii=False, indent=2), encoding='utf-8')
    credits = ['# Media credits', '', 'Third-party media retains its own license; repository code licensing does not replace it.', '']
    if report.get('output_license'):
        credits.extend(['Video composition license: '+report['output_license'], ''])
    for asset in registry:
        credits.extend([f"## {asset['id']} — {asset.get('title', '')}", '', asset.get('attribution', ''), '',
                        f"Source: {asset.get('source_url', '')}", '',
                        f"License: {asset.get('license', '')} {asset.get('license_url', '')}", '',
                        f"Changes: {asset.get('changes', 'See source registry.')}", ''])
    (output/'deck/MEDIA-CREDITS.md').write_text('\n'.join(credits), encoding='utf-8')
    return embedded
